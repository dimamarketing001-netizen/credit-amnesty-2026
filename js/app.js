  // ==== SCORE / RESULT ====
  function calcScore(){
    let score = 0;
    STEPS.forEach(s => {
      if(s.type !== 'question' || !s.options) return;
      const ans = state.answers[s.id];
      const opt = s.options.find(o => o.value === ans);
      if(opt) score += opt.score;
    });
    state.score = score;
  }

  function getResult(){
    // Расчёт диапазона списания на основе долга и общего score
    const debt = state.answers.debt;
    let minSum, maxSum, chance, verdict;

    // Базовые диапазоны по сумме долга
    const debtRanges = {
      'less-300':  [80000, 280000],
      '300-500':   [250000, 480000],
      '500-1500':  [500000, 1400000],
      '1500-plus': [1400000, 5000000]
    };
    [minSum, maxSum] = debtRanges[debt] || [300000, 800000];

    // Шанс на успех
    if(state.score >= 100){
      chance = 96;
      verdict = 'strong';
    } else if(state.score >= 75){
      chance = 88;
      verdict = 'good';
    } else if(state.score >= 55){
      chance = 78;
      verdict = 'medium';
    } else {
      chance = 65;
      verdict = 'need-consult';
    }

    return { minSum, maxSum, chance, verdict };
  }

