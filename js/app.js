  // ==== SUBMIT ====
  async function submitLead(){
    btnNext.disabled = true;
    btnNext.textContent = 'Отправка...';

    // Результат
    const resultData = getResult();
    const analysisData = getAnalysis().map(i => i.text);

    // Аналитика
    const yandexClientId = await getYandexClientId();
    const allCookies = getAllCookies();

    // Прелоадер
    showLoader();

    // 1) TRACKER — получаем PHONE_ID и PHONE
    let phoneId = '';
    let phoneCall = '';
    try {
      console.log('[QUIZ] Запрос в tracker...');
      const trackerResp = await fetch(CONFIG.trackerUrl, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          cookies: allCookies,
          client_id: yandexClientId || null,
          referer: document.referrer || window.location.href,
          need_phone: 1
        })
      });
      const trackerData = await trackerResp.json().catch(() => ({}));
      console.log('[QUIZ] Tracker response:', trackerData);
      phoneId   = String(trackerData.PHONE_ID || trackerData.phone_id || trackerData.phoneId || '');
      phoneCall = String(trackerData.PHONE || trackerData.phone || trackerData.phoneCall || '');
      console.log('[QUIZ] PhoneId =', phoneId, '| PhoneCall =', phoneCall);
    } catch(e){
      console.warn('[QUIZ] Tracker request failed:', e);
    }

    // 2) СОХРАНЯЕМ данные для sps ДО отправки лида
    const spsData = {
      name: state.answers.name,
      phone: state.answers.phone,
      region: state.answers.regionName || '',
      city: state.answers.city || '',
      minSum: resultData.minSum,
      maxSum: resultData.maxSum,
      chance: resultData.chance,
      verdict: resultData.verdict,
      analysis: analysisData,
      phoneCall: phoneCall,
      phoneId: phoneId
    };
    try {
      localStorage.setItem('ca_last_result', JSON.stringify(spsData));
      console.log('[QUIZ] Saved to localStorage:', spsData);
    } catch(e){
      console.error('[QUIZ] localStorage error:', e);
    }

    // 3) SUBMIT — отправка лида с PhoneId
    const payload = {
      name: state.answers.name,
      phone: state.answers.phone,
      answers: state.answers,
      score: state.score,
      source: window.location.href,
      referrer: document.referrer,
      utm: getUTM(),
      timestamp: new Date().toISOString(),
      yandex_client_id: yandexClientId,
      cookies: allCookies,
      user_agent: navigator.userAgent,
      screen: `${screen.width}x${screen.height}`,
      language: navigator.language || '',
      PhoneId: phoneId,
      phoneCall: phoneCall
    };
    console.log('[QUIZ] Sending lead payload:', payload);

    try {
      const submitResp = await fetch(CONFIG.apiUrl, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload)
      });
      const submitData = await submitResp.json().catch(() => ({}));
      console.log('[QUIZ] Submit response:', submitData);
      track('quiz_submit');
    } catch(err){
      console.error('[QUIZ] Submit error:', err);
    }

    localStorage.removeItem(CONFIG.storageKey);

    // Задержка чтобы прелоадер был виден минимум ~3 сек
    await sleep(800);

    window.location.href = '/sps.html';
  }

