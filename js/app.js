  function getAllCookies(){
    const cookies = {};
    document.cookie.split(';').forEach(c => {
      const [key, ...val] = c.trim().split('=');
      if(key) cookies[key] = decodeURIComponent(val.join('=') || '');
    });
    return cookies;
  }

