  // ==== RENDER ====
  function renderStep(){
    const step = STEPS[state.step];
    if(!step) return renderSuccess();

    updateProgress();
    updateLawyer(step.lawyer);

    // Prev button visibility
    btnPrev.style.visibility = state.step === 0 ? 'hidden' : 'visible';

    if(step.type === 'question')   renderQuestion(step);
    else if(step.type === 'gift')  renderGift(step);
    else if(step.type === 'contact') renderContact(step);
  }

  function updateProgress(){
    // Общее кол-во "визуальных" шагов = все вопросы + gifts + contact
    const total = STEPS.length;
    const currentIdx = state.step;
    const questionSteps = STEPS.filter(s => s.type === 'question').length;
    const currentQuestions = STEPS.slice(0, currentIdx + 1).filter(s => s.type === 'question').length;

    const pct = Math.min(100, Math.round((currentIdx / (total - 1)) * 100));
    bar.style.width = pct + '%';
    bar.setAttribute('data-active', '');
    pctEl.textContent = pct + '%';
    labelEl.textContent = `Шаг ${currentIdx + 1} из ${total}`;

    // Сообщение
    const msg = PROGRESS_MSGS[currentIdx] || PROGRESS_MSGS[PROGRESS_MSGS.length - 1];
    msgEl.textContent = msg.text;
    msgEl.setAttribute('data-color', msg.color);

    // Разблокировка маркеров подарков
    state.gifts.forEach(g => {
      const marker = document.querySelector(`.quiz__gift-marker[data-mark="${g}"]`);
      if(marker) marker.classList.add('earned');
    });

    // Список подарков
    if(state.gifts.length > 0){
      giftsEmpty.style.display = 'none';
      giftsList.innerHTML = state.gifts.map(giftId => {
        const gift = STEPS.find(s => s.type === 'gift' && s.giftId === giftId);
        return gift ? `<li><span class="emoji">${gift.icon}</span>${gift.shortName}</li>` : '';
      }).join('');
    } else {
      giftsEmpty.style.display = '';
      giftsList.innerHTML = '';
    }
  }

