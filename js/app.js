  function animateTodayCounter(){
    const el = document.getElementById('todayCount');
    if(!el) return;
    const today = new Date();
    const seed = today.getDate() + today.getMonth() * 31;
    const base = 32 + (seed % 25);
    let cur = 0;
    const step = () => {
      cur += Math.max(1, Math.floor((base - cur) / 8));
      if(cur >= base){ el.textContent = base; }
      else { el.textContent = cur; requestAnimationFrame(step); }
    };
    setTimeout(step, 300);
    setInterval(() => {
      const v = parseInt(el.textContent, 10) + 1;
      el.textContent = v;
    }, 120000);
  }

