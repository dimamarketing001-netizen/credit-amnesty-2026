const translitMap = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'e',
  ж: 'zh', з: 'z', и: 'i', й: 'y', к: 'k', л: 'l', м: 'm',
  н: 'n', о: 'o', п: 'p', р: 'r', с: 's', т: 't', у: 'u',
  ф: 'f', х: 'h', ц: 'ts', ч: 'ch', ш: 'sh', щ: 'sch',
  ъ: '', ы: 'y', ь: '', э: 'e', ю: 'yu', я: 'ya'
};

function isRegion(line) {
  return (
    /^Республика\s+/i.test(line) ||
    /\b(область|край|автономный округ|республика)\b/i.test(line)
  );
}

function slugify(str) {
  return str
    .toLowerCase()
    .split('')
    .map(ch => translitMap[ch] ?? ch)
    .join('')
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .replace(/_+/g, '_');
}

function unique(arr) {
  const seen = new Set();
  const result = [];

  for (const item of arr) {
    const value = item.trim();
    if (!value || seen.has(value)) continue;
    seen.add(value);
    result.push(value);
  }

  return result;
}

function getRegionKey(regionName) {
  if (REGION_KEYS[regionName]) return REGION_KEYS[regionName];

  return slugify(
    regionName
      .replace(/^Республика\s+/i, '')
      .replace(/\s+\(.*?\)/g, '')
      .replace(/\s+(область|край|автономный округ|республика)$/i, '')
      .trim()
  );
}

function getRegionDisplayName(regionName) {
  return REGION_NAME_OVERRIDES[regionName] || regionName;
}

function buildRegions(raw) {
  const lines = raw
    .split(/\r?\n/)
    .map(line => line.trim())
    .filter(Boolean)
    .filter(line => line !== 'Список городов и регионов России');

  const preRegionItems = [];
  const regionBlocks = [];
  let currentRegion = null;

  for (const line of lines) {
    if (isRegion(line)) {
      currentRegion = {
        name: line,
        cities: []
      };
      regionBlocks.push(currentRegion);
      continue;
    }

    if (!currentRegion) {
      preRegionItems.push(line);
    } else {
      currentRegion.cities.push(line);
    }
  }

  const hasMoscow = preRegionItems.includes('Москва');
  const hasSpb = preRegionItems.includes('Санкт-Петербург');

  const result = {};

  for (const region of regionBlocks) {
    let cities = unique(region.cities);

    if (region.name === 'Московская область' && hasMoscow) {
      cities = unique(['Москва', ...cities, 'Другой город']);
    } else if (region.name === 'Ленинградская область' && hasSpb) {
      cities = unique(['Санкт-Петербург', ...cities, 'Другой город']);
    } else {
      cities = unique([...cities, 'Другой город']);
    }

    result[getRegionKey(region.name)] = {
      name: getRegionDisplayName(region.name),
      cities
    };
  }

  if (hasMoscow && !result.moscow) {
    result.moscow = {
      name: 'Москва и область',
      cities: ['Москва', 'Другой город']
    };
  }

  if (hasSpb && !result.spb) {
    result.spb = {
      name: 'Санкт-Петербург и Ленобласть',
      cities: ['Санкт-Петербург', 'Другой город']
    };
  }

  return result;
}

function escapeString(str) {
  return String(str)
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'");
}

function toJs(value, level = 0) {
  const indent = '  '.repeat(level);
  const nextIndent = '  '.repeat(level + 1);

  if (Array.isArray(value)) {
    return `[${value.map(item => `'${escapeString(item)}'`).join(', ')}]`;
  }

  if (value && typeof value === 'object') {
    const entries = Object.entries(value).map(([key, val]) => {
      const safeKey = /^[a-zA-Z_$][a-zA-Z0-9_$]*$/.test(key) ? key : `'${key}'`;
      return `${nextIndent}${safeKey}: ${toJs(val, level + 1)}`;
    });

    return `{\n${entries.join(',\n')}\n${indent}}`;
  }

  return `'${escapeString(value)}'`;
}

